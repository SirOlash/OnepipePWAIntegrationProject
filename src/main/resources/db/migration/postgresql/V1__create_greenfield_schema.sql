-- Complete initial schema for an EMPTY PostgreSQL database/schema.
-- No seed data, automatic baseline, historical accounting adoption or collection backfill.
-- LocalDateTime uses timestamp without time zone; Instant uses timestamp with time zone.
-- Audit values and optimistic versions are written by Hibernate, not SQL triggers.

CREATE TABLE app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    email varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    role varchar(255),
    CONSTRAINT uk_app_users_email UNIQUE (email),
    CONSTRAINT ck_app_users_role CHECK (role IN ('SUPER_ADMIN', 'BRANCH_ADMIN', 'PARENT'))
);

CREATE TABLE parents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    user_id bigint,
    title varchar(255),
    first_name varchar(255),
    surname varchar(255),
    phone_number varchar(255),
    bank_account_number varchar(255),
    bank_code varchar(255),
    CONSTRAINT uk_parents_user UNIQUE (user_id),
    CONSTRAINT fk_parents_user FOREIGN KEY (user_id) REFERENCES app_users (id),
    CONSTRAINT ck_parents_title CHECK (title IN ('MR', 'MRS', 'MS', 'DR', 'CHIEF', 'ENGR', 'PROF', 'BARR'))
);

CREATE TABLE branches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    admin_user_id bigint,
    business_name varchar(255),
    business_short_name varchar(255),
    business_address varchar(255),
    rc_number varchar(255),
    tin varchar(255),
    contact_first_name varchar(255),
    contact_surname varchar(255),
    contact_email varchar(255),
    contact_phone_number varchar(255),
    whatsapp_number varchar(255),
    settlement_account_number varchar(255),
    settlement_bank_code varchar(255),
    request_ref varchar(255),
    transaction_ref varchar(255),
    biller_code varchar(255),
    CONSTRAINT uk_branches_admin_user UNIQUE (admin_user_id),
    CONSTRAINT uk_branches_rc_number UNIQUE (rc_number),
    CONSTRAINT uk_branches_request_ref UNIQUE (request_ref),
    CONSTRAINT uk_branches_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT fk_branches_admin_user FOREIGN KEY (admin_user_id) REFERENCES app_users (id)
);

CREATE TABLE students (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    first_name varchar(255) NOT NULL,
    surname varchar(255) NOT NULL,
    date_of_birth date,
    student_reg_id varchar(255) NOT NULL,
    class_grade varchar(255),
    branch_id bigint,
    parent_id bigint,
    number_of_payments integer,
    completed_payments integer,
    preferred_payment_type varchar(255),
    installment_frequency varchar(255),
    number_of_installments integer,
    CONSTRAINT uk_students_reg_id UNIQUE (student_reg_id),
    CONSTRAINT fk_students_branch FOREIGN KEY (branch_id) REFERENCES branches (id),
    CONSTRAINT fk_students_parent FOREIGN KEY (parent_id) REFERENCES parents (id),
    CONSTRAINT ck_students_class_grade CHECK (class_grade IN ('JSS1', 'JSS2', 'JSS3', 'SS1', 'SS2', 'SS3')),
    CONSTRAINT ck_students_payment_type CHECK (preferred_payment_type IN ('SINGLE_PAYMENT', 'INSTALLMENT', 'SUBSCRIPTION')),
    CONSTRAINT ck_students_frequency CHECK (installment_frequency IN ('DAILY', 'WEEKLY', 'MONTHLY'))
);

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    accounting_version integer,
    billing_anchor timestamp(6) without time zone,
    virtual_account_expired_at timestamp(6) with time zone,
    row_version bigint NOT NULL,
    student_id bigint,
    parent_id bigint,
    branch_id bigint,
    category varchar(255),
    payment_type varchar(255),
    status varchar(255),
    total_amount numeric(38,2),
    down_payment_amount numeric(38,2),
    amount_per_cycle numeric(38,2),
    installment_frequency varchar(255),
    number_of_payments integer,
    completed_payments integer,
    description varchar(255),
    request_ref varchar(255),
    transaction_ref varchar(255),
    one_pipe_payment_id varchar(255),
    virtual_account_number varchar(255),
    virtual_account_name varchar(255),
    virtual_account_bank_name varchar(255),
    virtual_account_bank_code varchar(255),
    one_pipe_reference varchar(255),
    customer_account_number varchar(255),
    virtual_account_expiry_date varchar(255),
    virtual_account_qr_code_url text,
    CONSTRAINT uk_payments_request_ref UNIQUE (request_ref),
    CONSTRAINT uk_payments_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT fk_payments_student FOREIGN KEY (student_id) REFERENCES students (id),
    CONSTRAINT fk_payments_parent FOREIGN KEY (parent_id) REFERENCES parents (id),
    CONSTRAINT fk_payments_branch FOREIGN KEY (branch_id) REFERENCES branches (id),
    CONSTRAINT ck_payments_category CHECK (category IN ('SCHOOL_FEES', 'ADHOC_PAYMENT')),
    CONSTRAINT ck_payments_type CHECK (payment_type IN ('SINGLE_PAYMENT', 'INSTALLMENT', 'SUBSCRIPTION')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUCCESSFUL', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_payments_frequency CHECK (installment_frequency IN ('DAILY', 'WEEKLY', 'MONTHLY'))
);

CREATE TABLE payment_collections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    event_id varchar(100) NOT NULL,
    payment_id bigint NOT NULL,
    transaction_ref varchar(100) NOT NULL,
    collection_slot varchar(50) NOT NULL,
    confirmed_amount numeric(38,2) NOT NULL,
    currency varchar(3) NOT NULL,
    source varchar(24) NOT NULL,
    confirmed_at timestamp(6) with time zone NOT NULL,
    collection_type varchar(24) NOT NULL,
    CONSTRAINT uk_collection_event UNIQUE (event_id),
    CONSTRAINT uk_collection_slot UNIQUE (payment_id, collection_slot),
    CONSTRAINT fk_collections_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT ck_collections_money CHECK (confirmed_amount > 0 AND currency = 'NGN'),
    CONSTRAINT ck_collections_source CHECK (source IN ('MOCK', 'VERIFIED_PROVIDER')),
    CONSTRAINT ck_collections_type CHECK (collection_type IN ('FULL', 'DOWN_PAYMENT', 'INSTALLMENT', 'SUBSCRIPTION_CYCLE'))
);

-- Unique constraints already index users' email, one-to-one FKs, invoice references,
-- and the ledger's payment_id/slot. PostgreSQL does not otherwise index FK columns.
CREATE INDEX ix_students_parent ON students (parent_id);
CREATE INDEX ix_students_branch ON students (branch_id);
CREATE INDEX ix_payments_parent ON payments (parent_id);
CREATE INDEX ix_payments_branch ON payments (branch_id);
CREATE INDEX ix_payments_student_category_status ON payments (student_id, category, status);
CREATE INDEX ix_payments_provider_id ON payments (one_pipe_payment_id);
CREATE INDEX ix_payments_status ON payments (status);
